describe("parseHometaxLines", () => {
  const r = parseHometaxLines(LINES);
  it("귀속연도·본인·소득기준 초과 부양가족", () => {
    expect(r.year).toBe(2025);
    expect(r.self).toBe("김본인");
    expect(r.overIncome).toEqual(["김부모"]);
  });
  it("보험 — 여러 쪽이면 마지막 쪽 인별합계, 소득기준 초과 가족은 기본으로 뺀다", () => {
    const ins = r.items.filter((x) => x.target === "insurance");
    expect(ins.map((x) => [x.person, x.amount, x.use])).toEqual([["김본인", 500_000, true], ["김부모", 700_000, false]]);
  });
  it("의료비 — 안경은 1인 50만까지, 소득기준 초과 가족도 의료비는 넣는다", () => {
    expect(r.items.find((x) => x.target === "medicalSelf")?.amount).toBe(700_000);
    expect(r.items.find((x) => x.target === "medicalOthers")).toMatchObject({ person: "김부모", amount: 50_000, use: true });
  });
  it("카드 — 신용 일반은 신용카드, 전통시장·대중교통 따로, 현금영수증 월세분은 일반(체크·현금)", () => {
    const s = sumPdfItems(r.items);
    expect(s["card.credit"]).toBe(10_000_000);           // 부모 카드 300만은 소득기준 초과라 빠짐
    expect(s["card.market"]).toBe(100_000);
    expect(s["card.transit"]).toBe(20_000);
    expect(s["card.debitCash"]).toBe(1_500_000);
  });
  it("건강보험은 넣지 않고 참고로만, 기부금은 칸 미정(켜 둔 채) → 고를 때까지 합계에 없다", () => {
    expect(r.info).toEqual([{ section: "건강보험료", amount: 1_100_000 }]);
    const don = r.items.find((x) => x.section === "기부금");
    expect(don).toMatchObject({ target: null, use: true, amount: 120_000 });
    expect(Object.keys(sumPdfItems(r.items)).some((k) => k.startsWith("don"))).toBe(false);
  });
});
